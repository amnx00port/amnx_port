<#
.SYNOPSIS
    Builds a portable Windows x64 release package of VIctory (victory.exe).

.DESCRIPTION
    Compiles VIctory in release mode (--locked) and assembles a self-contained
    Windows launcher folder outside git tracking (default: target\victory-windows)
    containing victory.exe, victory.example.toml, README.md, and a double-click
    Play-VIctory.cmd helper. Optionally runs `victory.exe doctor` to check the
    host PC's DirectX 12 / Shader Model 6.6 / Mesh Shader readiness.

    Copyrighted Xbox game files are never bundled. Point VIctory at your own
    legally obtained Xbox Series title dump via victory.toml, VICTORY_GAME_DIR,
    or by dragging-and-dropping the title's .exe onto victory.exe.

.PARAMETER OutDir
    Destination directory for the portable package (default: target\victory-windows).

.PARAMETER GameDir
    Optional path to your local Xbox title dump folder; writes a ready-to-use
    victory.toml inside the output folder pointing [paths].game_dir there.

.PARAMETER SkipDoctor
    Skip running `victory.exe doctor` after building.

.EXAMPLE
    .\scripts\build-windows.ps1
    .\scripts\build-windows.ps1 -GameDir "D:\XboxGames\MyTitle"
#>
[CmdletBinding()]
param(
    [string]$OutDir = "",
    [string]$GameDir = "",
    [switch]$SkipDoctor
)

$ErrorActionPreference = "Stop"

$RepoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
if ([string]::IsNullOrWhiteSpace($OutDir)) {
    $OutDir = Join-Path $RepoRoot "target\victory-windows"
}

Write-Host "==> Building VIctory (Windows x64 release)..." -ForegroundColor Cyan
Push-Location $RepoRoot
try {
    cargo build --release --locked -p victory
    if ($LASTEXITCODE -ne 0) {
        throw "cargo build failed with exit code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}

$ExeSrc = Join-Path $RepoRoot "target\release\victory.exe"
if (-not (Test-Path $ExeSrc)) {
    throw "Expected release binary at $ExeSrc"
}

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
Copy-Item -Force $ExeSrc (Join-Path $OutDir "victory.exe")
Copy-Item -Force (Join-Path $RepoRoot "victory.example.toml") (Join-Path $OutDir "victory.example.toml")
Copy-Item -Force (Join-Path $RepoRoot "README.md") (Join-Path $OutDir "README.md")

if (-not [string]::IsNullOrWhiteSpace($GameDir)) {
    $Escaped = $GameDir.Replace('\', '\\').Replace('"', '\"')
    $Toml = @"
# Generated by scripts/build-windows.ps1
[paths]
game_dir = "$Escaped"
"@
    Set-Content -Path (Join-Path $OutDir "victory.toml") -Value $Toml -Encoding UTF8
    Write-Host "==> Wrote victory.toml pointing at $GameDir" -ForegroundColor Green
}

$Cmd = @"
@echo off
setlocal
cd /d "%~dp0"
if "%~1"=="" (
    victory.exe
) else (
    victory.exe "%~1"
)
if errorlevel 1 pause
"@
Set-Content -Path (Join-Path $OutDir "Play-VIctory.cmd") -Value $Cmd -Encoding ASCII

Write-Host ""
Write-Host "==> Portable Windows package ready at:" -ForegroundColor Green
Write-Host "    $OutDir" -ForegroundColor White
Write-Host "    - Double-click victory.exe (or Play-VIctory.cmd) for the interactive launcher"
Write-Host "    - Or drag-and-drop any Xbox Series title .exe onto victory.exe"
Write-Host "    - Press F11 or Alt+Enter in-game for borderless fullscreen"
Write-Host ""

if (-not $SkipDoctor) {
    Write-Host "==> Running PC readiness check (victory.exe doctor)..." -ForegroundColor Cyan
    & (Join-Path $OutDir "victory.exe") doctor
}
